// Dynamic (layered Spine) illustrations — 动态立绘 (docs/OPERATOR-SKINS.md).
//
// The official skin table declares which outfits ship a layered illustration (`dynIllustId`). This
// tool keeps the shared catalogue's ILLUSTRATION_SPINES block in step with that table, and owns the
// source layout every installer uses: the `models_illust/` folder of isHarryh/Ark-Models (the same
// public dump docs/research/07-assets.md already names for illustration models).
//
//   models_illust/<folder>/<file>.{skel,atlas,png}
//   folder = dynIllustId with `char_` dropped after `dyn_illust_`  (dyn_illust_char_437_mizuki_sale#7
//            → dyn_illust_437_mizuki_sale#7)
//   file   = the full dynIllustId
//
// `--probe` reads that repository's tree once, so a catalogue entry only claims `verified` when the
// skeleton, atlas and a page are really there. Nothing is downloaded here; the files are installed
// into the (git-ignored) asset tree by tools/install-skins.mjs or the full plan
// (tools/assets/plan.mjs). Artwork never enters Git, and a missing file only disables the animated
// preview — the static illustration stays.
//
// CLI:
//   node tools/assets/illustrations.mjs           report the declarations (no network)
//   node tools/assets/illustrations.mjs --probe   verify the public dump and report
//   node tools/assets/illustrations.mjs --write   rewrite shared/skin-catalogue.js (combine with --probe
//                                                 to record the verified set)
//   node tools/assets/illustrations.mjs --check   fail when the block is stale

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const CATALOGUE = path.join(ROOT, 'shared', 'skin-catalogue.js');
const SKIN_TABLE = path.join(ROOT, '.cache', 'gamedata', 'excel', 'skin_table.json');
const TREE = 'https://api.github.com/repos/isHarryh/Ark-Models/git/trees/main?recursive=1';
const RAW = 'https://raw.githubusercontent.com/isHarryh/Ark-Models/main/models_illust/';
const BEGIN = '// >>> illustrations: dynamic layered Spine illustrations (generated by tools/assets/illustrations.mjs)';
const END = '// <<< illustrations';
const ID = /^dyn_illust_[A-Za-z0-9_@#.-]+$/;

/** The Ark-Models folder of one dynIllustId (the dump drops `char_` after `dyn_illust_`). */
export function illustrationFolder(id) {
  return typeof id === 'string' && ID.test(id) && !id.includes('..') ? id.replace(/^dyn_illust_char_/, 'dyn_illust_') : null;
}

/** Public source URLs of one illustration. `background` / `foreground` are optional and may be null. */
export function illustrationSources(id) {
  const folder = illustrationFolder(id);
  if (!folder) return null;
  const base = `${RAW}${encodeURIComponent(folder)}/${encodeURIComponent(id)}`;
  return { folder, skel: `${base}.skel`, atlas: `${base}.atlas`, page: `${base}.png`, background: null, foreground: null };
}

/** The official `dynIllustId` of one skin, or null. */
export function officialIllustrationId(skin) {
  const raw = skin?.dynIllustId || null;
  return typeof raw === 'string' && ID.test(raw) ? raw : null;
}

/** Catalogue official ids, in the order the catalogue lists them. */
export function catalogueOfficialIds(source) {
  return [...String(source).matchAll(/"officialId": "([^"]+)"/g)].map((m) => m[1]);
}

/**
 * One row per catalogue outfit the official table gives a layered illustration.
 * @param {{ source: string, skinTable: any }} p
 * @returns {{ id: string, officialId: string, verified: boolean, background: boolean, foreground: boolean }[]}
 */
export function illustrationRows({ source, skinTable }) {
  const table = skinTable?.charSkins || {};
  const rows = [];
  for (const officialId of catalogueOfficialIds(source)) {
    const dyn = officialIllustrationId(table[officialId]);
    if (dyn) rows.push({ id: dyn, officialId, verified: false, background: false, foreground: false });
  }
  return rows;
}

/** Read the verified flags already recorded in the block (so a write without --probe never forgets them). */
export function recordedRows(source) {
  const body = blockBody(source);
  const rows = [];
  if (!body) return rows;
  for (const line of body.split('\n')) {
    const m = /^  "([^"]+)": Object\.freeze\(\{ id: "([^"]+)"(.*) \}\),$/.exec(line);
    if (m) rows.push({ officialId: m[1], id: m[2], verified: /verified: true/.test(m[3]), background: /background: true/.test(m[3]), foreground: /foreground: true/.test(m[3]) });
  }
  return rows;
}

function blockBody(source) {
  const text = String(source);
  const a = text.indexOf(BEGIN);
  const b = text.indexOf(END);
  return a >= 0 && b > a ? text.slice(a + BEGIN.length, b) : null;
}

/** `Object.freeze({ ... })` source for one row. */
function rowLine(row) {
  const parts = [`id: ${JSON.stringify(row.id)}`];
  if (row.verified) parts.push('verified: true');
  if (row.background) parts.push('background: true');
  if (row.foreground) parts.push('foreground: true');
  return `  ${JSON.stringify(row.officialId)}: Object.freeze({ ${parts.join(', ')} }),`;
}

export function renderIllustrationBlock(rows) {
  return [
    BEGIN,
    '// Metadata only: no resource URL lives here. `verified` means the public Ark-Models dump carries the skeleton,',
    '// atlas and page (tools/assets/illustrations.mjs --probe); the installer still checks every file before it writes',
    '// a manifest entry, and a missing file leaves the static illustration in place. Background / foreground layers are',
    '// optional: when a record carries neither, the component draws the Spine layer alone.',
    'export const ILLUSTRATION_SPINES = Object.freeze({',
    ...rows.map(rowLine),
    '});',
    END,
  ].join('\n');
}

/** Replace (or append) the block. Returns the new source. */
export function withIllustrationBlock(source, rows) {
  const text = String(source);
  const a = text.indexOf(BEGIN);
  const b = text.indexOf(END);
  const block = renderIllustrationBlock(rows);
  if (a >= 0 && b > a) {
    const after = b + END.length;
    return `${text.slice(0, a)}${block}${text.slice(after)}`;
  }
  const tail = text.endsWith('\n') ? text : `${text}\n`;
  return `${tail}\n${block}\n`;
}

/** Merge recorded flags into freshly derived rows (declarations that disappeared are dropped). */
export function mergeRecorded(rows, recorded) {
  const byId = new Map(recorded.map((r) => [r.officialId, r]));
  return rows.map((r) => {
    const old = byId.get(r.officialId);
    return old && old.id === r.id ? { ...r, verified: old.verified, background: old.background, foreground: old.foreground } : r;
  });
}

async function readTree(fetchImpl) {
  const res = await fetchImpl(TREE, { headers: { 'User-Agent': 'Stronghold-Protocol illustration cataloguer' } });
  if (!res.ok) throw new Error(`Ark-Models tree HTTP ${res.status}`);
  const json = await res.json();
  return new Set((json.tree || []).map((x) => x.path));
}

/**
 * Check the declarations against the public dump's tree (one request). A row is verified when the
 * folder holds the skeleton, atlas and page. Optional background / foreground layers are recorded
 * separately; the dump does not carry them today.
 */
export async function probeIllustrations(rows, { fetchImpl = globalThis.fetch } = {}) {
  const paths = await readTree(fetchImpl);
  for (const row of rows) {
    const src = illustrationSources(row.id);
    if (!src) continue;
    const have = (suffix) => paths.has(`models_illust/${src.folder}/${row.id}${suffix}`);
    row.verified = have('.skel') && have('.atlas') && have('.png');
    row.background = row.verified && src.background ? paths.has(`models_illust/${src.folder}/${row.id}_bg.png`) : false;
    row.foreground = row.verified && src.foreground ? paths.has(`models_illust/${src.folder}/${row.id}_fg.png`) : false;
  }
  return rows;
}

export async function readInputs({ catalogue = CATALOGUE, skinTable = SKIN_TABLE } = {}) {
  const [source, tableText] = await Promise.all([readFile(catalogue, 'utf8'), readFile(skinTable, 'utf8').catch(() => '{}')]);
  return { source, skinTable: JSON.parse(tableText) };
}

async function main() {
  const args = new Set(process.argv.slice(2));
  const { source, skinTable } = await readInputs();
  const rows = mergeRecorded(illustrationRows({ source, skinTable }), recordedRows(source));
  if (args.has('--probe')) await probeIllustrations(rows);
  const verified = rows.filter((r) => r.verified).length;
  const next = withIllustrationBlock(source, rows);
  if (args.has('--check') && next !== source) {
    console.error(`illustrations: ${CATALOGUE} is stale (${rows.length} declarations, ${verified} verified) — run node tools/assets/illustrations.mjs --write --probe`);
    process.exitCode = 1;
    return;
  }
  if (args.has('--write')) {
    if (next !== source) await writeFile(CATALOGUE, next);
    console.log(`illustrations: ${rows.length} declared, ${verified} verified → ${path.relative(ROOT, CATALOGUE)}`);
    return;
  }
  console.log(`illustrations: ${rows.length} declared, ${verified} verified`);
  for (const r of rows) console.log(`  ${r.verified ? '●' : '○'} ${r.officialId}  ${r.id}${r.background ? '  bg' : ''}${r.foreground ? '  fg' : ''}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((e) => { console.error(e?.stack || e); process.exitCode = 1; });
}
